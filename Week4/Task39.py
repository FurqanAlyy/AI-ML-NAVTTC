# NumPy Sorting Arrays

import numpy as np
arr = np.array([3, 2, 0, 1])

print(np.sort(arr))

# example 1

arr = np.array(['banana', 'cherry', 'apple'])
print(np.sort(arr))

# example 2

arr = np.array([True, False, True])
print(np.sort(arr))

# Sorting a 2-D Array

arr = np.array([[3, 2, 4], [5, 0, 1]])
print(np.sort(arr))